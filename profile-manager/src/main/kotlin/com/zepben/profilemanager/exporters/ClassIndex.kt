package com.zepben.profilemanager.exporters

import com.zepben.profilemanager.models.Class
import com.zepben.profilemanager.models.Element

/**
 * A class from the spec, along with the site relative URL of its documentation page, and the packages it's in.
 */
data class IndexedClass(val cls: Class, val url: String, val packagePath: List<String> = emptyList())

/**
 * Lookup of the classes in a profile by name, shared by the class pages and the diagrams so both agree on where each
 * class's page is.
 */
class ClassIndex(private val byName: Map<String, IndexedClass>, private val sharedNames: Map<String, List<IndexedClass>> = emptyMap()) {

    operator fun get(name: String): IndexedClass? = byName[name]

    /** The class called [name] in the package nearest [from], or the one [get] finds if there's no nearest. */
    fun get(name: String, from: List<String>): IndexedClass? {
        val byNearness = sharedNames[name]?.groupBy { it.packagePath.zip(from).takeWhile { (a, b) -> a == b }.size }
        return byNearness?.maxBy { it.key }?.value?.singleOrNull() ?: byName[name]
    }

    /** The class called [name] in the package nearest the class [from], see [get]. */
    fun get(name: String, from: Class): IndexedClass? =
        get(name, (sharedNames[from.name] ?: listOfNotNull(byName[from.name])).firstOrNull { it.cls === from }?.packagePath.orEmpty())

    operator fun contains(name: String): Boolean = name in byName

    /** The URL of the page of the class called [name], if there is one. */
    fun urlOf(name: String): String? = byName[name]?.url

    val classes: Collection<Class> get() = byName.values.map { it.cls }

    /** The URL of every class page. */
    val urls: Set<String> by lazy { byName.values.mapTo(mutableSetOf()) { it.url } }

    companion object {

        /** An index of [classes], each with a page at `/<name>`. */
        fun of(vararg classes: Class): ClassIndex = ClassIndex(classes.associate { it.name to IndexedClass(it, "/${it.name}") })

        /**
         * Index every class under [root], each with the URL of its page as generated by [Docusaurus2Mdx]:
         * `/<linkPrefix>/<root>/<package>/.../<class>`. If two classes share a name, the last one wins unless another is nearer.
         */
        fun of(root: Element, linkPrefix: String, warn: (String) -> Unit = ::printWarning): ClassIndex {
            val byName = mutableMapOf<String, IndexedClass>()
            val all = mutableListOf<IndexedClass>()
            fun visit(e: Element, path: String, packages: List<String>) {
                if (e is Class) {
                    val url = "$path/${e.name}"
                    byName.put(e.name, IndexedClass(e, url, packages).also(all::add))?.let {
                        warn("duplicate class name '${e.name}' found at ${it.url} and $url, keeping $url unless another is nearer.")
                    }
                } else
                    e.children.forEach { visit(it, "$path/${e.name}", if (e === root) packages else packages + e.name) }
            }
            visit(root, sitePath(linkPrefix), emptyList())

            return ClassIndex(byName, all.groupBy { it.cls.name }.filterValues { it.size > 1 })
        }

    }

}
